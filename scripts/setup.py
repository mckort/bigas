#!/usr/bin/env python3
"""
Interactive setup wizard for Bigas local MVP.

Guides new users through the minimum configuration needed to run Bigas
locally with in-memory chat storage — no GCP, Firebase, or Discord required.

Usage:
    python scripts/setup.py
"""
from __future__ import annotations

import argparse
import os
import sys
from datetime import datetime, timezone

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENV_PATH = os.path.join(REPO_ROOT, ".env")

MVP_DEFAULTS = {
    "SECRET_MANAGER": "false",
    "FLASK_ENV": "development",
    "FLASK_DEBUG": "false",
    "PORT": "8080",
    "SERVER_URL": "http://localhost:8080",
    "CHAT_ENABLED": "true",
    "CHAT_STORAGE_MODE": "memory",
    "CHAT_AUTH_MODE": "dev",
    "CHAT_DEV_TOKEN": "bigas-dev-token",
}

LLM_MODELS = {
    "gemini": "gemini-3.1-pro-preview",
    "openai": "gpt-4o",
    "anthropic": "claude-sonnet-5",
}

# answer field → env var written into .env
_LLM_KEYS = {
    "gemini": ("gemini_api_key", "GEMINI_API_KEY"),
    "openai": ("openai_api_key", "OPENAI_API_KEY"),
    "anthropic": ("anthropic_api_key", "ANTHROPIC_API_KEY"),
}


def _prompt(message: str, default: str = "") -> str:
    suffix = f" [{default}]" if default else ""
    while True:
        try:
            value = input(f"{message}{suffix}: ").strip()
        except (EOFError, KeyboardInterrupt):
            print("\nSetup cancelled.")
            sys.exit(1)
        if value:
            return value
        if default:
            return default
        print("  Please enter a value (or Ctrl+C to cancel).")


def _prompt_yes_no(message: str, default: bool = False) -> bool:
    hint = "Y/n" if default else "y/N"
    while True:
        try:
            raw = input(f"{message} ({hint}): ").strip().lower()
        except (EOFError, KeyboardInterrupt):
            print("\nSetup cancelled.")
            sys.exit(1)
        if not raw:
            return default
        if raw in ("y", "yes"):
            return True
        if raw in ("n", "no"):
            return False
        print("  Please answer y or n.")


def _prompt_secret(message: str) -> str:
    """Read a secret; fall back to visible input when getpass is unavailable."""
    try:
        import getpass

        while True:
            try:
                value = getpass.getpass(f"{message}: ").strip()
            except (EOFError, KeyboardInterrupt):
                print("\nSetup cancelled.")
                sys.exit(1)
            if value:
                return value
            print("  Please enter a value (or Ctrl+C to cancel).")
    except Exception:
        return _prompt(message)


def build_env_lines(answers: dict) -> list[str]:
    """Build .env file lines from wizard answers."""
    lines: list[str] = [
        "# Generated by scripts/setup.py",
        f"# {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}",
        "",
        "# --- Local MVP defaults (no GCP / Firebase required) ---",
    ]
    for key, value in MVP_DEFAULTS.items():
        lines.append(f"{key}={value}")

    provider = answers.get("llm_provider", "gemini")
    lines.extend(
        [
            "",
            "# --- LLM (required) ---",
            f"LLM_MODEL={answers.get('llm_model', LLM_MODELS[provider])}",
        ]
    )
    answer_field, env_name = _LLM_KEYS.get(provider, _LLM_KEYS["gemini"])
    lines.append(f"{env_name}={answers[answer_field]}")

    optional_sections: list[tuple[str, list[str]]] = []

    if answers.get("enable_github"):
        optional_sections.append(
            (
                "GitHub (CTO agent — PR review, autofix)",
                [f"GITHUB_TOKEN={answers['github_token']}"],
            )
        )

    if answers.get("enable_jira"):
        optional_sections.append(
            (
                "Jira (Product agent — release notes, board automation)",
                [
                    f"JIRA_BASE_URL={answers['jira_base_url']}",
                    f"JIRA_EMAIL={answers['jira_email']}",
                    f"JIRA_API_TOKEN={answers['jira_api_token']}",
                    f"JIRA_PROJECT_KEY={answers['jira_project_key']}",
                    f"JIRA_AUTOMATION_WEBHOOK_SECRET={answers.get('jira_webhook_secret', 'change-me-local-dev')}",
                ],
            )
        )

    if answers.get("enable_discord"):
        discord_lines = []
        if answers.get("discord_marketing"):
            discord_lines.append(f"DISCORD_WEBHOOK_URL_MARKETING={answers['discord_marketing']}")
        if answers.get("discord_product"):
            discord_lines.append(f"DISCORD_WEBHOOK_URL_PRODUCT={answers['discord_product']}")
        if answers.get("discord_cto"):
            discord_lines.append(f"DISCORD_WEBHOOK_URL_CTO={answers['discord_cto']}")
        if discord_lines:
            optional_sections.append(("Discord (notifications)", discord_lines))

    if answers.get("enable_ga4"):
        optional_sections.append(
            (
                "Google Analytics 4 (Marketing agent)",
                [
                    f"GOOGLE_PROJECT_ID={answers['google_project_id']}",
                    f"GA4_PROPERTY_ID={answers['ga4_property_id']}",
                    f"GOOGLE_SERVICE_ACCOUNT_EMAIL={answers.get('google_service_account_email', '')}",
                ],
            )
        )

    if answers.get("enable_cursor"):
        optional_sections.append(
            (
                "Cursor (CTO autofix via cloud agents)",
                [f"CURSOR_API_KEY={answers['cursor_api_key']}"],
            )
        )

    carried = []
    for field, env_name in (
        ("bigas_access_keys", "BIGAS_ACCESS_KEYS"),
        ("github_webhook_secret", "GITHUB_WEBHOOK_SECRET"),
        ("bigas_public_url", "BIGAS_PUBLIC_URL"),
        ("bigas_features", "BIGAS_FEATURES"),
    ):
        if answers.get(field):
            carried.append(f"{env_name}={answers[field]}")
    if carried:
        optional_sections.append(("Copied from the environment", carried))

    for title, section_lines in optional_sections:
        lines.extend(["", f"# --- {title} ---", *section_lines])

    lines.extend(
        [
            "",
            "# --- Optional: add more integrations from env.example ---",
            "# cp env.example .env.full && merge any keys you need",
            "",
        ]
    )
    return lines


def write_env_file(path: str, lines: list[str], overwrite: bool) -> None:
    if os.path.exists(path) and not overwrite:
        raise FileExistsError(path)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
        if not lines[-1].endswith("\n"):
            fh.write("\n")


def run_wizard() -> dict:
    print()
    print("=" * 60)
    print("  Bigas setup — local MVP in under 5 minutes")
    print("=" * 60)
    print()
    print("This wizard creates a minimal .env for local evaluation:")
    print("  • In-memory chat (no Firebase)")
    print("  • Dev login (any email + bigas-dev-token)")
    print("  • Only the LLM API key is required")
    print()

    if os.path.exists(ENV_PATH):
        if not _prompt_yes_no(f"{ENV_PATH} already exists. Overwrite?", default=False):
            print("Keeping existing .env — nothing changed.")
            sys.exit(0)

    print("\n--- Step 1: LLM provider (required) ---")
    provider = _prompt("Provider: gemini, openai, or anthropic", "gemini").lower()
    if provider not in LLM_MODELS:
        print(f"  Unknown provider '{provider}', using gemini.")
        provider = "gemini"

    answers: dict = {"llm_provider": provider}
    _secret_prompts = {
        "openai": "OpenAI API key",
        "anthropic": "Anthropic API key",
        "gemini": "Gemini API key",
    }
    field, _env_name = _LLM_KEYS[provider]
    answers[field] = _prompt_secret(_secret_prompts[provider])

    custom_model = _prompt("LLM model (leave default to skip)", LLM_MODELS[provider])
    if custom_model != LLM_MODELS[provider]:
        answers["llm_model"] = custom_model

    print("\n--- Step 2: Optional specialists ---")
    print("Enable only what you need — you can re-run this script anytime.\n")

    if _prompt_yes_no("Enable CTO agent? (GitHub PR review)", default=False):
        answers["enable_github"] = True
        answers["github_token"] = _prompt_secret("GitHub personal access token (repo scope)")

    if _prompt_yes_no("Enable Product agent? (Jira release notes & automation)", default=False):
        answers["enable_jira"] = True
        answers["jira_base_url"] = _prompt("Jira base URL (e.g. https://yourco.atlassian.net)")
        answers["jira_email"] = _prompt("Jira account email")
        answers["jira_api_token"] = _prompt_secret("Jira API token")
        answers["jira_project_key"] = _prompt("Jira project key (e.g. BIG)")

    if _prompt_yes_no("Enable Marketing agent? (GA4 analytics)", default=False):
        answers["enable_ga4"] = True
        answers["google_project_id"] = _prompt("Google Cloud project ID")
        answers["ga4_property_id"] = _prompt("GA4 property ID (numeric)")
        answers["google_service_account_email"] = _prompt(
            "Service account email (for GA4 API)", ""
        )

    if _prompt_yes_no("Send reports to Discord?", default=False):
        answers["enable_discord"] = True
        if _prompt_yes_no("  Marketing Discord webhook?", default=True):
            answers["discord_marketing"] = _prompt_secret("  DISCORD_WEBHOOK_URL_MARKETING")
        if _prompt_yes_no("  Product Discord webhook?", default=False):
            answers["discord_product"] = _prompt_secret("  DISCORD_WEBHOOK_URL_PRODUCT")
        if _prompt_yes_no("  CTO Discord webhook?", default=False):
            answers["discord_cto"] = _prompt_secret("  DISCORD_WEBHOOK_URL_CTO")

    if answers.get("enable_github") and _prompt_yes_no(
        "Enable Cursor autofix for failed PRs?", default=False
    ):
        answers["enable_cursor"] = True
        answers["cursor_api_key"] = _prompt_secret("Cursor API key")

    return answers


def answers_from_env(provider: str = "", model: str = "", environ=None) -> dict:
    """Build wizard answers from the process environment. No prompts.

    Returns {} when no LLM key is set, or {"missing": provider} when --provider
    names a key that is empty. Never includes a key that was not set.
    """
    env = environ if environ is not None else os.environ
    present = {
        name: (env.get(env_name) or "").strip()
        for name, (_field, env_name) in _LLM_KEYS.items()
    }
    provider = (provider or "").strip().lower()
    if provider and provider not in LLM_MODELS:
        raise ValueError(f"Unknown provider {provider!r}. Use gemini, openai, or anthropic.")
    if provider and not present[provider]:
        return {"missing": provider}
    if not provider:
        if present["gemini"]:
            provider = "gemini"
        else:
            provider = next((name for name, value in present.items() if value), "")
    if not provider:
        return {}
    field, _env_name = _LLM_KEYS[provider]
    answers: dict = {"llm_provider": provider, field: present[provider]}
    if model.strip():
        answers["llm_model"] = model.strip()
    github = (env.get("GITHUB_TOKEN") or "").strip()
    if github:
        answers["enable_github"] = True
        answers["github_token"] = github
    cursor = (env.get("CURSOR_API_KEY") or "").strip()
    if cursor:
        answers["enable_cursor"] = True
        answers["cursor_api_key"] = cursor
    for field_name, env_name in (
        ("bigas_access_keys", "BIGAS_ACCESS_KEYS"),
        ("github_webhook_secret", "GITHUB_WEBHOOK_SECRET"),
        ("bigas_public_url", "BIGAS_PUBLIC_URL"),
        ("bigas_features", "BIGAS_FEATURES"),
    ):
        value = (env.get(env_name) or "").strip()
        if value:
            answers[field_name] = value
    return answers


def _print_wrote(path: str, answers: dict) -> None:
    print()
    print("=" * 60)
    print(f"  Wrote {path}")
    print("=" * 60)
    print()
    copied = []
    if answers.get("enable_github"):
        copied.append("GITHUB_TOKEN")
    if answers.get("enable_cursor"):
        copied.append("CURSOR_API_KEY")
    for field_name, env_name in (
        ("bigas_access_keys", "BIGAS_ACCESS_KEYS"),
        ("github_webhook_secret", "GITHUB_WEBHOOK_SECRET"),
        ("bigas_public_url", "BIGAS_PUBLIC_URL"),
        ("bigas_features", "BIGAS_FEATURES"),
    ):
        if answers.get(field_name):
            copied.append(env_name)
    if copied:
        print("Also copied from the environment (values not shown): " + ", ".join(copied))
        print()
    print("Next steps:")
    print("  1. docker compose up --build")
    print("     # or: python run_core.py  (after pip install -r requirements.txt)")
    print("  2. Open http://localhost:8080")
    print("  3. Sign in with any email and token: bigas-dev-token")
    print()
    print("Portfolio: python scripts/discover_portfolio.py")
    print("Cloud Run: python scripts/setup_cloud.py --project YOUR_PROJECT_ID")
    print()


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--noninteractive",
        action="store_true",
        help="Write .env from the environment. No prompts. Needs GEMINI_API_KEY, OPENAI_API_KEY, or ANTHROPIC_API_KEY.",
    )
    parser.add_argument("--provider", default="", help="gemini, openai, or anthropic (default: gemini if that key is set)")
    parser.add_argument("--model", default="", help="LLM_MODEL override")
    parser.add_argument("--force", action="store_true", help="Overwrite an existing .env")
    parser.add_argument("--env-file", default=ENV_PATH, help="Where to write (default: .env)")
    args = parser.parse_args(argv)

    if not args.noninteractive:
        answers = run_wizard()
        lines = build_env_lines(answers)
        write_env_file(ENV_PATH, lines, overwrite=True)
        _print_wrote(ENV_PATH, answers)
        return 0

    if os.path.exists(args.env_file) and not args.force:
        print(f"{args.env_file} already exists. Left it alone. Pass --force to rewrite it.")
        return 0
    try:
        answers = answers_from_env(args.provider, args.model)
    except ValueError as exc:
        print(f"✗ {exc}")
        return 2
    if not answers or answers.get("missing"):
        which = answers.get("missing") if answers else ""
        print("No LLM key in the environment. Export one and rerun. Do not commit it.")
        print("  GEMINI_API_KEY=... python scripts/setup.py --noninteractive")
        print("  # or OPENAI_API_KEY, or ANTHROPIC_API_KEY")
        if which:
            print(f"  --provider {which} is set, but that key is empty.")
        return 2
    lines = build_env_lines(answers)
    write_env_file(args.env_file, lines, overwrite=True)
    _print_wrote(args.env_file, answers)
    return 0


if __name__ == "__main__":
    sys.exit(main())
